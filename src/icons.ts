export function iconSvg(kind: ModuleKind, id?: string): string {
  const key = (id && GLYPHS[id] ? id : KIND_GLYPH[kind]) ?? "armor";
  return bitmap(GLYPHS[key] ?? GLYPHS.armor);
}
