import type { ModuleKind } from "./types";

function bitmap(rows: readonly string[]): string {
  const rects: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === "#") rects.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`);
    }
  });
  return `<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${rects.join("")}</svg>`;
}

